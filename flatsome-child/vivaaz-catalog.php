/**
 * Filter products by stone key (e.g. 'ruby', 'sapphire', 'moonstone', 'garnet')
 */
function vivaaz_get_products_by_stone($stone_key) {
    $stone_key = strtolower(trim($stone_key));
    if ($stone_key === 'all' || empty($stone_key)) {
        return vivaaz_get_master_catalog();
    }
    
    // Normalization mapping
    $aliases = array(
        'moonstone'         => 'rainbow-moonstone',
        'rainbow-moonstone' => 'rainbow-moonstone',
        'blue-sapphire'     => 'sapphire',
        'rhodolite'         => 'garnet',
        'rhodolite-garnet'  => 'garnet',
        'swiss-topaz'       => 'topaz',
        'blue-topaz'        => 'topaz',
    );
    if (isset($aliases[$stone_key])) {
        $stone_key = $aliases[$stone_key];
    }

    $all = vivaaz_get_master_catalog();
    $matched = array();
    foreach ($all as $item) {
        if ($item['stone'] === $stone_key) {
            $matched[] = $item;
        }
    }

    // If no direct stone products exist, fall back to matching items
    return $matched;
}

/**
 * Filter products by group ('precious' or 'semi')
 */
function vivaaz_get_products_by_group($group) {
    $group = strtolower(trim($group));
    if (strpos($group, 'semi') !== false) {
        $group = 'semi';
    } elseif (strpos($group, 'precious') !== false) {
        $group = 'precious';
    }

    $all = vivaaz_get_master_catalog();
    $matched = array();
    foreach ($all as $item) {
        if ($item['group'] === $group) {
            $matched[] = $item;
        }
    }
    return $matched;
}

/**
 * Find single product by slug or ID
 */
function vivaaz_get_product_by_slug_or_id($needle) {
    $needle = strtolower(trim($needle));
    $all = vivaaz_get_master_catalog();
    
    foreach ($all as $item) {
        if (strtolower($item['slug']) === $needle || strtolower($item['code']) === $needle || strtolower($item['id']) === $needle) {
            return $item;
        }
    }

    // Secondary match: substring in slug
    foreach ($all as $item) {
        if (strpos($item['slug'], $needle) !== false || strpos($needle, $item['stone']) !== false) {
            return $item;
        }
    }

    return null;
}
